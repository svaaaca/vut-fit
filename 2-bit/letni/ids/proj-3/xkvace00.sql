-- CREATE TABLES (vytvoreni objektu databaze)
CREATE TABLE urednik (
    osobni_cislo INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL PRIMARY KEY,
    jmeno VARCHAR(32) NOT NULL,
    prijmeni VARCHAR(32) NOT NULL,
    datum_narozeni DATE NOT NULL,
    pohlavi VARCHAR(16) NOT NULL,
    slechticky_titul VARCHAR(16)
);

CREATE TABLE uzemni_pusobnost (
    katastralni_cislo NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000 INCREMENT BY 1) NOT NULL PRIMARY KEY,
    kralovstvi VARCHAR(32),
    zeme VARCHAR(32),
    region VARCHAR(32),
    hrabstvi VARCHAR(32),
    okres VARCHAR(32),
    obec VARCHAR(32),

    -- kontrola formatu katastralniho cisla:
    -- 1) prvni cislice musi byt pouze 1 nebo 2 (druh cislovani)
    -- 2) nasleduje peticiferne kmenove cislo
    -- 3) dalsi tri cislice vyjadruji poddeleni
    -- 4) a posledni cislice znaci atribut parcely
    CHECK(REGEXP_LIKE(katastralni_cislo, '^[1-2][0-9]{9}$'))
);

-- vztah generalizace/specializace: urad i skola spadaji pod entitu instituce
-- (instituce nemodelovana - pouze tabulky pro podtypy i s atributy nadtypu),
-- tzn. obe entity dedi vsechny atributy, navic skola obsahuje atributy
-- obor, stupen a akademicky titul (v pripade uradu jsou tyto atributy irelevantni)
CREATE TABLE urad (
    zkratka NUMBER(3) GENERATED BY DEFAULT AS IDENTITY (START WITH 001 INCREMENT BY 1) NOT NULL PRIMARY KEY,
    fk_urad_uzemni_pusobnost NUMBER(10) NOT NULL,
    nazev VARCHAR(64) NOT NULL,
    sidlo VARCHAR(32) NOT NULL,
    typ VARCHAR(32) NOT NULL,
    datum_zrizeni DATE NOT NULL,
    zrizovaci_dokument VARCHAR(64),
    datum_zaniku DATE,

    CONSTRAINT fk_urad_uzemni_pusobnost FOREIGN KEY(fk_urad_uzemni_pusobnost) REFERENCES uzemni_pusobnost(katastralni_cislo),

    -- kontrola dat, zda nasleduji chronologicky za sebou
    CHECK(datum_zrizeni <= datum_zaniku)
);

CREATE TABLE skola (
    zkratka NUMBER(3) GENERATED BY DEFAULT AS IDENTITY (START WITH 001 INCREMENT BY 1) NOT NULL PRIMARY KEY,
    fk_skola_uzemni_pusobnost NUMBER(10) NOT NULL,
    nazev VARCHAR(64) NOT NULL,
    sidlo VARCHAR(32) NOT NULL,
    typ VARCHAR(32) NOT NULL,
    datum_zrizeni DATE NOT NULL,
    zrizovaci_dokument VARCHAR(64),
    datum_zaniku DATE,
    obor VARCHAR(64) NOT NULL,
    stupen NUMBER(2) NOT NULL,
    akademicky_titul VARCHAR(16),

    CONSTRAINT fk_skola_uzemni_pusobnost FOREIGN KEY(fk_skola_uzemni_pusobnost) REFERENCES uzemni_pusobnost(katastralni_cislo),

    -- kontrola dat, zda nasleduji chronologicky za sebou
    -- a zda je stupen vyssi cislo nez 0
    CHECK(datum_zrizeni <= datum_zaniku),
    CHECK(stupen > 0)
);

CREATE TABLE rozhodnuti (
    jednaci_cislo INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL PRIMARY KEY,
    fk_rozhodnuti_urednik INTEGER NOT NULL,
    fk_rozhodnuti_urad NUMBER(3),
    fk_rozhodnuti_skola NUMBER(3),
    datum_rozhodnuti DATE NOT NULL,
    datum_vykonatelnosti DATE NOT NULL,
    text_vlastniho_rozhodnuti VARCHAR(128) NOT NULL,
    text_oduvodneni VARCHAR(256) NOT NULL,

    CONSTRAINT fk_rozhodnuti_urednik FOREIGN KEY(fk_rozhodnuti_urednik) REFERENCES urednik(osobni_cislo),
    CONSTRAINT fk_rozhodnuti_urad FOREIGN KEY(fk_rozhodnuti_urad) REFERENCES urad(zkratka),
    CONSTRAINT fk_rozhodnuti_skola FOREIGN KEY(fk_rozhodnuti_skola) REFERENCES skola(zkratka),

    -- kontrola dat, zda nasleduji chronologicky za sebou
    -- a jestli rozhodnuti spada pod urad nebo skolu
    CHECK(datum_rozhodnuti <= datum_vykonatelnosti),
    CHECK(fk_rozhodnuti_urad IS NOT NULL OR fk_rozhodnuti_skola IS NOT NULL)
);

CREATE TABLE funkce (
    kod INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL PRIMARY KEY,
    fk_urad INTEGER,
    fk_skola INTEGER,
    nazev VARCHAR(32) NOT NULL,
    zpusob_ziskani VARCHAR(32) NOT NULL,
    delka_funkcniho_obdobi INTEGER NOT NULL,
    datum_zavedeni DATE NOT NULL,
    datum_zruseni DATE,

    CONSTRAINT fk_urad FOREIGN KEY(fk_urad) REFERENCES urad(zkratka),
    CONSTRAINT fk_skola FOREIGN KEY(fk_skola) REFERENCES skola(zkratka),

    -- kontrola, jestli je delka funkcniho obdobi validni cislo,
    -- zda data nasleduji chronologicky za sebou
    -- a jestli funkce spada pod urad nebo skolu
    CHECK(delka_funkcniho_obdobi > 0),
    CHECK(datum_zavedeni <= datum_zruseni),
    CHECK(fk_urad IS NOT NULL OR fk_skola IS NOT NULL)
);

CREATE TABLE zastava (
    fk_zastava_osobni_cislo INTEGER NOT NULL,
    fk_zastava_kod INTEGER NOT NULL,
    datum_zacatku DATE NOT NULL,
    datum_konce DATE,
    duvod_opusteni VARCHAR(32),
    poradi_obsazeni INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    CONSTRAINT fk_zastava_osobni_cislo FOREIGN KEY(fk_zastava_osobni_cislo) REFERENCES urednik(osobni_cislo),
    CONSTRAINT fk_zastava_kod FOREIGN KEY(fk_zastava_kod) REFERENCES funkce(kod),

    -- kontrola dat, zda nasleduji chronologicky za sebou
    -- a jestli je poradi obsazeni validni cislo
    CHECK(datum_zacatku <= datum_konce),
    CHECK(poradi_obsazeni > 0)
);

CREATE TABLE studuje (
    fk_studuje_osobni_cislo INTEGER NOT NULL,
    fk_studuje_zkratka NUMBER(3) NOT NULL,
    datum_zacatku DATE NOT NULL,
    datum_konce DATE,
    uspesne_zakonceni VARCHAR(16),

    CONSTRAINT fk_studuje_osobni_cislo FOREIGN KEY(fk_studuje_osobni_cislo) REFERENCES urednik(osobni_cislo),
    CONSTRAINT fk_studuje_zkratka FOREIGN KEY(fk_studuje_zkratka) REFERENCES skola(zkratka),

    -- kontrola dat, zda nasleduji chronologicky za sebou
    CHECK(datum_zacatku <= datum_konce)
);

