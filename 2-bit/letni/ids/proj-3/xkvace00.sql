-- dotaz, ktery vybere vsechny funkce zavedene na danem urade (Cesky telekomunikacni urad) serazene podle delky funkcniho obdobi [spojeni dvou tabulek]
SELECT DISTINCT funkce.nazev AS funkce, urad.nazev AS urad, funkce.delka_funkcniho_obdobi FROM funkce JOIN urad ON funkce.fk_urad = urad.zkratka WHERE urad.nazev = 'Český telekomunikační úřad' ORDER BY funkce.delka_funkcniho_obdobi DESC;

-- dotaz, ktery vybere vsechny urady se sidlem v dane obci (Brno) serazene podle data zrizeni [spojeni dvou tabulek]
SELECT DISTINCT urad.nazev AS urad, uzemni_pusobnost.obec AS sidlo, urad.datum_zrizeni FROM uzemni_pusobnost JOIN urad ON uzemni_pusobnost.katastralni_cislo = urad.fk_urad_uzemni_pusobnost WHERE uzemni_pusobnost.obec = 'Brno' ORDER BY urad.datum_zrizeni;

-- dotaz, ktery vybere vsechny uredniky, kteri provedli rozhodnuti spadajici pod urcitou skolu (Vysoke uceni technicke v Brne) serazene podle prijmeni [spojeni tri tabulek]
SELECT DISTINCT urednik.jmeno, urednik.prijmeni, skola.nazev AS skola FROM urednik JOIN rozhodnuti ON urednik.osobni_cislo = rozhodnuti.fk_rozhodnuti_urednik JOIN skola ON rozhodnuti.fk_rozhodnuti_skola = skola.zkratka WHERE skola.nazev = 'Vysoké učení technické v Brně' ORDER BY urednik.prijmeni;

-- dotaz, ktery vybere vsechny uredniky, kteri zastavaji nejakou funkci serazene podle poctu zastavanych funkci [klauzule GROUP BY s agregacni funkci COUNT]
SELECT DISTINCT urednik.jmeno, urednik.prijmeni, COUNT(urednik.osobni_cislo) AS pocet_funkci FROM urednik JOIN zastava ON urednik.osobni_cislo = zastava.fk_zastava_osobni_cislo GROUP BY urednik.jmeno, urednik.prijmeni ORDER BY pocet_funkci DESC;

-- dotaz, ktery vybere vsechny urady, pod ktere spadaji rozhodnuti ucinena pred urcitym datem (01.01.2022) serazene podle poctu rozhodnuti [klauzule GROUP BY s agregacni funkci COUNT]
SELECT DISTINCT urad.nazev AS urad, COUNT(rozhodnuti.fk_rozhodnuti_urad) AS pocet_rozhodnuti FROM urad JOIN rozhodnuti ON urad.zkratka = rozhodnuti.fk_rozhodnuti_urad WHERE rozhodnuti.datum_rozhodnuti < TO_DATE('01.01.2022', 'dd.mm.yyyy') GROUP BY urad.nazev ORDER BY pocet_rozhodnuti DESC;

-- dotaz, ktery vybere vsechny uredniky, kteri dosud neudelali zadne rozhodnuti serazene podle prijmeni [predikat EXISTS]
SELECT DISTINCT urednik.jmeno, urednik.prijmeni FROM urednik WHERE NOT EXISTS(SELECT * FROM rozhodnuti WHERE rozhodnuti.fk_rozhodnuti_urednik = urednik.osobni_cislo) ORDER BY urednik.prijmeni;

-- dotaz, ktery vybere vsechna rozhodnuti spadajici pod urcitou skolu (Vysoke uceni technicke v Brne) serazena podle data rozhodnuti [predikat IN]
SELECT DISTINCT skola.nazev AS skola, rozhodnuti.text_vlastniho_rozhodnuti, rozhodnuti.datum_rozhodnuti FROM rozhodnuti JOIN skola ON rozhodnuti.fk_rozhodnuti_skola = skola.zkratka WHERE rozhodnuti.fk_rozhodnuti_skola IN(SELECT skola.zkratka FROM skola WHERE skola.nazev = 'Vysoké učení technické v Brně') ORDER BY rozhodnuti.datum_rozhodnuti;

